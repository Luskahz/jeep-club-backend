-- BACK-549 isolated catalog. No legacy rows, tables or physical objects are changed.
CREATE TABLE storage_media_assets (
    id BIGINT NOT NULL AUTO_INCREMENT,
    origin VARCHAR(24) NOT NULL,
    source_context VARCHAR(32) NOT NULL,
    source_record_id VARCHAR(128) NULL,
    uploaded_by_user_id BIGINT NULL,
    owner_user_id BIGINT NULL,
    subject_type VARCHAR(16) NOT NULL,
    subject_id BIGINT NULL,
    purpose VARCHAR(64) NOT NULL,
    classification VARCHAR(24) NOT NULL,
    physical_state VARCHAR(16) NOT NULL,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    version BIGINT NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT ck_storage_asset_subject CHECK ((subject_type = 'UNKNOWN' AND subject_id IS NULL) OR (subject_type IN ('USER','DEPENDENT') AND subject_id IS NOT NULL AND subject_id > 0)),
    CONSTRAINT ck_storage_asset_dates CHECK (updated_at >= created_at),
    CONSTRAINT ck_storage_asset_version CHECK (version >= 0),
    CONSTRAINT ck_storage_asset_uploader CHECK (uploaded_by_user_id IS NULL OR uploaded_by_user_id > 0),
    CONSTRAINT ck_storage_asset_owner CHECK (owner_user_id IS NULL OR owner_user_id > 0),
    CONSTRAINT ck_storage_asset_origin CHECK (origin IN ('UNKNOWN','UPLOAD','LEGACY_IMPORT')),
    CONSTRAINT ck_storage_asset_source_context CHECK (source_context IN ('UNKNOWN','IDENTITY_PROFILE','VEHICLE_PHOTO','PUBLICATION_IMAGE','PUBLICATION_COMMENT','EVENT_IMAGE','TOOL_IMAGE','DEPENDENT_PHOTO')),
    CONSTRAINT ck_storage_asset_subject_type CHECK (subject_type IN ('UNKNOWN','USER','DEPENDENT')),
    CONSTRAINT ck_storage_asset_classification CHECK (classification IN ('UNCLASSIFIED','CLASSIFIED')),
    CONSTRAINT ck_storage_asset_physical_state CHECK (physical_state IN ('UNKNOWN','PRESENT','MISSING')),
    INDEX ix_storage_asset_uploader (uploaded_by_user_id,id),
    INDEX ix_storage_asset_subject (subject_type,subject_id,id),
    INDEX ix_storage_asset_owner (owner_user_id,id),
    INDEX ix_storage_asset_classification (classification,id)
) ENGINE=InnoDB;

CREATE TABLE storage_media_variants (
    id BIGINT NOT NULL AUTO_INCREMENT,
    media_id BIGINT NOT NULL,
    variant_code VARCHAR(64) CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_bin NOT NULL,
    role VARCHAR(16) NOT NULL,
    provider VARCHAR(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_bin NOT NULL,
    namespace VARCHAR(64) CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_bin NOT NULL,
    storage_key VARCHAR(512) CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_bin NOT NULL,
    mime_type VARCHAR(127) NOT NULL,
    size_bytes BIGINT NOT NULL,
    width INT NULL,
    height INT NULL,
    checksum_algorithm VARCHAR(32) NULL,
    checksum VARCHAR(128) NULL,
    preset_code VARCHAR(64) NULL,
    processing_version VARCHAR(64) NULL,
    transformation_code VARCHAR(64) NULL,
    created_at DATETIME(6) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_storage_variant_code UNIQUE (media_id, variant_code),
    CONSTRAINT uk_storage_variant_location UNIQUE (provider, namespace, storage_key),
    CONSTRAINT uk_storage_variant_target UNIQUE (media_id, id),
    CONSTRAINT ck_storage_variant_size CHECK (size_bytes >= 0),
    CONSTRAINT ck_storage_variant_dimensions CHECK ((width IS NULL AND height IS NULL) OR (width IS NOT NULL AND height IS NOT NULL AND width > 0 AND height > 0)),
    CONSTRAINT ck_storage_variant_checksum CHECK ((checksum_algorithm IS NULL AND checksum IS NULL) OR (checksum_algorithm IS NOT NULL AND checksum IS NOT NULL)),
    CONSTRAINT ck_storage_variant_master CHECK ((role = 'MASTER' AND variant_code = 'MASTER') OR (role = 'DERIVED' AND variant_code NOT IN ('MASTER','ORIGINAL'))),
    CONSTRAINT ck_storage_variant_role CHECK (role IN ('MASTER','DERIVED')),
    CONSTRAINT fk_storage_variant_asset FOREIGN KEY (media_id) REFERENCES storage_media_assets(id) ON DELETE RESTRICT ON UPDATE RESTRICT
) ENGINE=InnoDB;

CREATE TABLE storage_media_references (
    id BIGINT NOT NULL AUTO_INCREMENT,
    media_id BIGINT NOT NULL,
    context VARCHAR(32) NOT NULL,
    consumer_id VARCHAR(128) NOT NULL,
    role VARCHAR(64) NOT NULL,
    position INT NULL,
    association_origin VARCHAR(24) NOT NULL,
    linked_at DATETIME(6) NOT NULL,
    linked_by_user_id BIGINT NULL,
    unlinked_at DATETIME(6) NULL,
    unlinked_by_user_id BIGINT NULL,
    unlink_reason_code VARCHAR(64) NULL,
    version BIGINT NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_storage_reference_target UNIQUE (media_id, id),
    CONSTRAINT ck_storage_reference_dates CHECK (unlinked_at IS NULL OR unlinked_at >= linked_at),
    CONSTRAINT ck_storage_reference_end CHECK (unlinked_at IS NOT NULL OR (unlinked_by_user_id IS NULL AND unlink_reason_code IS NULL)),
    CONSTRAINT ck_storage_reference_position CHECK (position IS NULL OR position >= 0),
    CONSTRAINT ck_storage_reference_version CHECK (version >= 0),
    CONSTRAINT ck_storage_reference_known_context CHECK (context <> 'UNKNOWN'),
    CONSTRAINT ck_storage_reference_link_actor CHECK (linked_by_user_id IS NULL OR linked_by_user_id > 0),
    CONSTRAINT ck_storage_reference_unlink_actor CHECK (unlinked_by_user_id IS NULL OR unlinked_by_user_id > 0),
    CONSTRAINT ck_storage_reference_context CHECK (context IN ('UNKNOWN','IDENTITY_PROFILE','VEHICLE_PHOTO','PUBLICATION_IMAGE','PUBLICATION_COMMENT','EVENT_IMAGE','TOOL_IMAGE','DEPENDENT_PHOTO')),
    CONSTRAINT ck_storage_reference_association_origin CHECK (association_origin IN ('UNKNOWN','UPLOAD','LEGACY_IMPORT')),
    CONSTRAINT fk_storage_reference_asset FOREIGN KEY (media_id) REFERENCES storage_media_assets(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    INDEX ix_storage_reference_consumer (context,consumer_id,unlinked_at,id),
    INDEX ix_storage_reference_asset (media_id,unlinked_at,id)
) ENGINE=InnoDB;

CREATE TABLE storage_media_audit_events (
    id BIGINT NOT NULL AUTO_INCREMENT,
    media_id BIGINT NOT NULL,
    variant_id BIGINT NULL,
    reference_id BIGINT NULL,
    operation VARCHAR(32) NOT NULL,
    actor_kind VARCHAR(16) NOT NULL,
    actor_user_id BIGINT NULL,
    occurred_at DATETIME(6) NOT NULL,
    correlation_id VARCHAR(64) NULL,
    previous_version BIGINT NULL,
    resulting_version BIGINT NULL,
    PRIMARY KEY (id),
    CONSTRAINT ck_storage_audit_actor CHECK ((actor_kind = 'USER' AND actor_user_id IS NOT NULL AND actor_user_id > 0) OR (actor_kind IN ('UNKNOWN','SYSTEM') AND actor_user_id IS NULL)),
    CONSTRAINT ck_storage_audit_target CHECK (variant_id IS NULL OR reference_id IS NULL),
    CONSTRAINT ck_storage_audit_versions CHECK ((previous_version IS NULL OR previous_version >= 0) AND (resulting_version IS NULL OR resulting_version >= 0)),
    CONSTRAINT ck_storage_auditevent_operation CHECK (operation IN ('ASSET_REGISTERED','ASSET_METADATA_UPDATED','VARIANT_REGISTERED','REFERENCE_RECORDED','REFERENCE_ENDED')),
    CONSTRAINT ck_storage_auditevent_actor_kind CHECK (actor_kind IN ('UNKNOWN','USER','SYSTEM')),
    CONSTRAINT fk_storage_auditevent_asset FOREIGN KEY (media_id) REFERENCES storage_media_assets(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_storage_audit_variant FOREIGN KEY (media_id, variant_id) REFERENCES storage_media_variants(media_id, id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_storage_audit_reference FOREIGN KEY (media_id, reference_id) REFERENCES storage_media_references(media_id, id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    INDEX ix_storage_audit_asset (media_id,occurred_at,id)
) ENGINE=InnoDB;
